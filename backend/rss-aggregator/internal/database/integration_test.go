func TestUpdateItemKeepsTheRow(t *testing.T) {
	queries, ctx := setup(t)

	feed := createFeed(t, queries, ctx, "feed", "https://example.com/a.xml")
	channel := createChannel(t, queries, ctx, feed, "channel")
	item := createItem(t, queries, ctx, channel, itemFields{guid: "g1", title: "before", seeders: 1})

	updated, err := queries.UpdateItem(ctx, database.UpdateItemParams{
		ID:        item.ID,
		Guid:      "g1",
		Title:     sql.NullString{String: "after", Valid: true},
		Seeders:   sql.NullInt32{Int32: 99, Valid: true},
		UpdatedAt: time.Now().UTC(),
		ChannelID: channel.ID,
	})

	if err != nil {
		t.Fatalf("UpdateItem: %v", err)
	}

	if updated.ID != item.ID {
		t.Errorf("UpdateItem created a new row: %s vs %s", updated.ID, item.ID)
	}

	if updated.Seeders.Int32 != 99 || updated.Title.String != "after" {
		t.Errorf("row not updated: seeders=%d title=%q", updated.Seeders.Int32, updated.Title.String)
	}
}

// listItems fills a channel with a known set of items, so the filters can be
// checked against a fixed expectation.
func seedItems(t *testing.T, queries *database.Queries, ctx context.Context) database.Channel {
	t.Helper()

	feed := createFeed(t, queries, ctx, "feed", "https://example.com/a.xml")
	channel := createChannel(t, queries, ctx, feed, "channel")

	base := time.Date(2024, 6, 25, 10, 0, 0, 0, time.UTC)

	createItem(t, queries, ctx, channel, itemFields{
		guid: "g1", title: "[SubsPlease] Alpha", category: "Anime", seeders: 1000, publishedAt: base,
	})
	createItem(t, queries, ctx, channel, itemFields{
		guid: "g2", title: "[Erai-raws] Beta", category: "Anime", seeders: 50, publishedAt: base.Add(-time.Hour),
	})
	createItem(t, queries, ctx, channel, itemFields{
		guid: "g3", title: "[Other] Gamma", category: "Live Action", seeders: 500, publishedAt: base.Add(-2 * time.Hour),
	})

	return channel
}

