// Package database_test exercises the sqlc-generated queries against a real
// PostgreSQL instance. Everything here is skipped unless TEST_DATABASE_URL is
// set, so `go test ./...` stays runnable without a database.
package database_test

import (
	"context"
	"database/sql"
	"errors"
	"fmt"
	"os"
	"testing"
	"time"

	"rss-aggregator/internal/database"

	"github.com/google/uuid"
	_ "github.com/jackc/pgx/v5/stdlib"
	"github.com/pressly/goose/v3"
)

var (
	testDB      *sql.DB
	testQueries *database.Queries
)

func TestMain(m *testing.M) {
	databaseURL := os.Getenv("TEST_DATABASE_URL")

	if databaseURL == "" {
		// No database configured: every test skips itself.
		os.Exit(m.Run())
	}

	db, err := sql.Open("pgx", databaseURL)
	if err != nil {
		fmt.Fprintf(os.Stderr, "cannot open the test database: %v\n", err)
		os.Exit(1)
	}

	if err := db.Ping(); err != nil {
		fmt.Fprintf(os.Stderr, "cannot reach the test database: %v\n", err)
		os.Exit(1)
	}

	// The tests run against the real schema, applied by the same migrations
	// that production uses.
	if err := goose.SetDialect("postgres"); err != nil {
		fmt.Fprintf(os.Stderr, "goose dialect: %v\n", err)
		os.Exit(1)
	}

	goose.SetLogger(goose.NopLogger())

	if err := goose.Up(db, "../../sql/schema"); err != nil {
		fmt.Fprintf(os.Stderr, "applying migrations: %v\n", err)
		os.Exit(1)
	}

	testDB = db
	testQueries = database.New(db)

	code := m.Run()

	db.Close()
	os.Exit(code)
}

// setup gives each test an empty database.
func setup(t *testing.T) (*database.Queries, context.Context) {
	t.Helper()

	if testQueries == nil {
		t.Skip("TEST_DATABASE_URL is not set")
	}

	if _, err := testDB.Exec("TRUNCATE items, channels, feed_follows, feeds, users RESTART IDENTITY CASCADE"); err != nil {
		t.Fatalf("truncating: %v", err)
	}

	return testQueries, context.Background()
}

