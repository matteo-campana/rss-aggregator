func TestListItemsFilters(t *testing.T) {
	queries, ctx := setup(t)
	channel := seedItems(t, queries, ctx)

	tests := []struct {
		name   string
		params database.ListItemsParams
		want   []string
	}{
		{
			name:   "no filter",
			params: database.ListItemsParams{},
			want:   []string{"g1", "g2", "g3"},
		},
		{
			name:   "search is case insensitive and partial",
			params: database.ListItemsParams{Search: sql.NullString{String: "erai", Valid: true}},
			want:   []string{"g2"},
		},
		{
			name:   "category",
			params: database.ListItemsParams{Category: sql.NullString{String: "Live Action", Valid: true}},
			want:   []string{"g3"},
		},
		{
			name:   "min seeders",
			params: database.ListItemsParams{MinSeeders: sql.NullInt32{Int32: 500, Valid: true}},
			want:   []string{"g1", "g3"},
		},
		{
			name:   "channel",
			params: database.ListItemsParams{ChannelID: uuid.NullUUID{UUID: channel.ID, Valid: true}},
			want:   []string{"g1", "g2", "g3"},
		},
		{
			name:   "another channel matches nothing",
			params: database.ListItemsParams{ChannelID: uuid.NullUUID{UUID: uuid.New(), Valid: true}},
			want:   []string{},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			rows := listItems(t, queries, ctx, tt.params)

			got := make([]string, 0, len(rows))
			for _, row := range rows {
				got = append(got, row.Guid)
			}

			if len(got) != len(tt.want) {
				t.Fatalf("got %v, want %v", got, tt.want)
			}

			seen := map[string]bool{}
			for _, guid := range got {
				seen[guid] = true
			}

			for _, guid := range tt.want {
				if !seen[guid] {
					t.Errorf("got %v, want it to contain %q", got, guid)
				}
			}
		})
	}
}

