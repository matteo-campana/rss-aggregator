// The scraper picks the feeds it has not seen in the longest time, and a feed
// that was never fetched has to come first.
func TestGetNextFeedsToFetchPutsNeverFetchedFirst(t *testing.T) {
	queries, ctx := setup(t)

	fetched := createFeed(t, queries, ctx, "already fetched", "https://example.com/a.xml")
	never := createFeed(t, queries, ctx, "never fetched", "https://example.com/b.xml")

	if _, err := queries.MarkFeedAsFetched(ctx, fetched.ID); err != nil {
		t.Fatalf("MarkFeedAsFetched: %v", err)
	}

	feeds, err := queries.GetNextFeedsToFetch(ctx, 10)
	if err != nil {
		t.Fatalf("GetNextFeedsToFetch: %v", err)
	}

	if len(feeds) != 2 {
		t.Fatalf("got %d feeds, want 2", len(feeds))
	}

	if feeds[0].ID != never.ID {
		t.Errorf("first feed = %q, want the never fetched one", feeds[0].Name)
	}

	if !feeds[1].LastFetchedAt.Valid {
		t.Error("MarkFeedAsFetched left last_fetched_at NULL")
	}
}

