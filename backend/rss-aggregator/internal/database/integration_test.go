// The regression this locks in: a GUID is unique per channel, not globally, so
// two feeds carrying the same torrent each keep their own row.
func TestSameGuidCanExistInTwoChannels(t *testing.T) {
	queries, ctx := setup(t)

	feedA := createFeed(t, queries, ctx, "feed A", "https://example.com/a.xml")
	feedB := createFeed(t, queries, ctx, "feed B", "https://example.com/b.xml")

	channelA := createChannel(t, queries, ctx, feedA, "channel A")
	channelB := createChannel(t, queries, ctx, feedB, "channel B")

	const guid = "https://nyaa.si/view/1800001"

	createItem(t, queries, ctx, channelA, itemFields{guid: guid, title: "in A", seeders: 10})
	createItem(t, queries, ctx, channelB, itemFields{guid: guid, title: "in B", seeders: 20})

	inA, err := queries.GetItemByChannelIdAndGuid(ctx, database.GetItemByChannelIdAndGuidParams{
		ChannelID: channelA.ID,
		Guid:      guid,
	})

	if err != nil {
		t.Fatalf("looking the item up in channel A: %v", err)
	}

	inB, err := queries.GetItemByChannelIdAndGuid(ctx, database.GetItemByChannelIdAndGuidParams{
		ChannelID: channelB.ID,
		Guid:      guid,
	})

	if err != nil {
		t.Fatalf("looking the item up in channel B: %v", err)
	}

	if inA.ID == inB.ID {
		t.Fatal("both channels resolve to the same row: the GUID is still globally unique")
	}

	if inA.Title.String != "in A" || inB.Title.String != "in B" {
		t.Errorf("rows got mixed up: %q / %q", inA.Title.String, inB.Title.String)
	}
}

