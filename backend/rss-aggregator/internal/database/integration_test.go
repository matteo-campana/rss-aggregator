func TestUserLifecycle(t *testing.T) {
	queries, ctx := setup(t)

	user := createUser(t, queries, ctx, "Matteo Campana")

	// The API key is generated by a column default, not by the application.
	if len(user.ApiKey) != 64 {
		t.Errorf("api key = %q, want 64 hex characters generated by the database", user.ApiKey)
	}

	found, err := queries.GetUserByApiKey(ctx, user.ApiKey)
	if err != nil {
		t.Fatalf("GetUserByApiKey: %v", err)
	}

	if found.ID != user.ID {
		t.Errorf("GetUserByApiKey returned %s, want %s", found.ID, user.ID)
	}

	if _, err := queries.GetUserByApiKey(ctx, "not-a-key"); !errors.Is(err, sql.ErrNoRows) {
		t.Errorf("GetUserByApiKey with an unknown key = %v, want sql.ErrNoRows", err)
	}

	if err := queries.DeleteUser(ctx, user.ID); err != nil {
		t.Fatalf("DeleteUser: %v", err)
	}

	if _, err := queries.GetUser(ctx, user.ID); !errors.Is(err, sql.ErrNoRows) {
		t.Errorf("GetUser after delete = %v, want sql.ErrNoRows", err)
	}
}

