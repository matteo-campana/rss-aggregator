// The security regression: every feed-follow query is scoped by user_id, so one
// user's key can never reach another user's rows.
func TestFeedFollowsAreScopedToTheirUser(t *testing.T) {
	queries, ctx := setup(t)

	alice := createUser(t, queries, ctx, "Alice")
	bob := createUser(t, queries, ctx, "Bob")
	feed := createFeed(t, queries, ctx, "feed", "https://example.com/a.xml")

	follow, err := queries.CreateFeedFollow(ctx, database.CreateFeedFollowParams{
		ID:        uuid.New(),
		CreatedAt: time.Now().UTC(),
		UpdatedAt: time.Now().UTC(),
		UserID:    bob.ID,
		FeedID:    feed.ID,
	})

	if err != nil {
		t.Fatalf("CreateFeedFollow: %v", err)
	}

	if _, err := queries.GetFeedFollowByIdAndUserId(ctx, database.GetFeedFollowByIdAndUserIdParams{
		ID:     follow.ID,
		UserID: alice.ID,
	}); !errors.Is(err, sql.ErrNoRows) {
		t.Errorf("Alice reading Bob's follow = %v, want sql.ErrNoRows", err)
	}

	if _, err := queries.GetFeedFollowsByUserIdAndFeedId(ctx, database.GetFeedFollowsByUserIdAndFeedIdParams{
		UserID: alice.ID,
		FeedID: feed.ID,
	}); !errors.Is(err, sql.ErrNoRows) {
		t.Errorf("Alice reading Bob's follow by feed = %v, want sql.ErrNoRows", err)
	}

	aliceFollows, err := queries.GetFeedsFollowsByUserId(ctx, alice.ID)
	if err != nil {
		t.Fatalf("GetFeedsFollowsByUserId: %v", err)
	}

	if len(aliceFollows) != 0 {
		t.Errorf("Alice sees %d follows, want none of Bob's", len(aliceFollows))
	}

	// A delete aimed at somebody else's row must not remove it.
	if err := queries.DeleteFeedFollowByIdAndUserId(ctx, database.DeleteFeedFollowByIdAndUserIdParams{
		ID:     follow.ID,
		UserID: alice.ID,
	}); err != nil {
		t.Fatalf("DeleteFeedFollowByIdAndUserId: %v", err)
	}

	if _, err := queries.GetFeedFollowByIdAndUserId(ctx, database.GetFeedFollowByIdAndUserIdParams{
		ID:     follow.ID,
		UserID: bob.ID,
	}); err != nil {
		t.Errorf("Bob's follow disappeared after Alice's delete: %v", err)
	}

	// Bob deleting his own does work.
	if err := queries.DeleteFeedFollowByIdAndUserId(ctx, database.DeleteFeedFollowByIdAndUserIdParams{
		ID:     follow.ID,
		UserID: bob.ID,
	}); err != nil {
		t.Fatalf("Bob deleting his own follow: %v", err)
	}

	if _, err := queries.GetFeedFollowByIdAndUserId(ctx, database.GetFeedFollowByIdAndUserIdParams{
		ID:     follow.ID,
		UserID: bob.ID,
	}); !errors.Is(err, sql.ErrNoRows) {
		t.Errorf("follow still there after Bob deleted it = %v, want sql.ErrNoRows", err)
	}
}

